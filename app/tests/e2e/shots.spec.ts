// Not assertions: walks through the app and saves pictures for review.
import { test, type Page } from '@playwright/test'
import { openDemo, pickDemo, plugInNew, runSplitWizard, special } from './helpers'

test.use({ colorScheme: 'dark' })

const dir = process.env.SHOTS ?? 'test-results/shots'
const shot = (page: Page, name: string) => page.screenshot({ path: `${dir}/${name}.png` })

test('walk through the macro pad setup', async ({ page }) => {
  await page.goto('/')
  await page.waitForSelector('[data-test=demos]')
  await page.waitForTimeout(700)
  await shot(page, '01-home')
  await pickDemo(page, 'macropad')
  await page.waitForTimeout(700)
  await shot(page, '01b-bench')
  await plugInNew(page)
  await page.waitForSelector('[data-test=special]')
  await page.waitForTimeout(900)
  await shot(page, '02-keys')
  await special(page, 'open-board')
  await page.waitForTimeout(500)
  await shot(page, '03-board')
  await page.click('[data-test=next]')
  await special(page, 'explain')
  await page.waitForTimeout(500)
  await shot(page, '04-explain')
  await page.click('[data-test=close-pins]')
  await page.waitForTimeout(900)
  const keys = page.locator('[data-test=virtual-board] .key')
  for (let i = 0; i < 6; i++) {
    await keys.nth(i).dispatchEvent('pointerdown')
    await page.waitForTimeout(160)
    if (i === 3) await shot(page, '05-keys-pressing')
    await page.dispatchEvent('body', 'pointerup')
    await page.waitForTimeout(120)
  }
  await shot(page, '06-keys-done')
  await page.click('[data-test=next]')
  await page.click('[data-test=row-key-1-2]')
  await page.waitForTimeout(500)
  await shot(page, '07-rows')
  await page.click('[data-test=next]')
  for (const first of [0, 3]) {
    await page.locator(`[data-test=letters-board] [data-pos="${first}"]`).dispatchEvent('pointerdown')
    await page.dispatchEvent('body', 'pointerup')
  }
  await page.waitForTimeout(500)
  await shot(page, '07b-letters')
  await page.click('[data-test=next]')
  await page.waitForSelector('[data-test=rename]')
  await page.waitForTimeout(800)
  await shot(page, '08-editor')
})

test('editor tabs', async ({ page }) => {
  await openDemo(page, 'split')
  await page.waitForSelector('[data-test=found-other]', { timeout: 20_000 })
  await shot(page, '09-split-keys')
  await runSplitWizard(page)
  await page.waitForTimeout(500)
  await page.locator('[data-test=keymap-board] [data-pos="2"]').dispatchEvent('pointerdown')
  await page.check('[data-test=hold-tap]')
  await page.waitForTimeout(400)
  await shot(page, '10-keymap')
  await page.click('[data-test=picker-fold]')
  await shot(page, '10a-keymap-minimised')
  await page.click('[data-test=picker-fold]')
  await page.locator('[data-test=keymap-board] [data-pos="5"]').dispatchEvent('pointerdown')
  await page.locator('[data-test=keymap-board] [data-pos="6"]').dispatchEvent('pointerdown', { shiftKey: true })
  await page.locator('[data-test=keymap-board] [data-pos="7"]').dispatchEvent('pointerdown', { shiftKey: true })
  await page.click('[data-test=tab-layers]')
  await page.waitForTimeout(300)
  await shot(page, '10b-keymap-several')
  await page.locator('[data-test=keymap-board] [data-pos="0"]').dispatchEvent('pointerdown')
  await page.click('[data-test=tab-macros]')
  await page.click('[data-test=macro-0]')
  await page.fill('[data-test=macro-name]', 'Copy all')
  await page.keyboard.press('Enter')
  await page.click('[data-test=macro-by-hand]')
  await page.fill('[data-test=macro-text]', 'Hi!')
  await page.click('[data-test=macro-add-text]')
  await page.click('[data-test=macro-by-hand]')
  await page.waitForTimeout(400)
  await shot(page, '10c-keymap-macro')
  for (const tab of ['layout', 'behaviours', 'hardware', 'share']) {
    await page.click(`[data-test=nav-${tab}]`)
    await page.waitForTimeout(600)
    await shot(page, `11-${tab}`)
  }
  await page.click('[data-test=nav-behaviours]')
  await page.click('[data-test=section-macros]')
  await page.click('[data-test=macro-slot-0]')
  await page.waitForTimeout(400)
  await shot(page, '12-macros')
})
